import numpy as np, json, pathlib
import essentia.standard as es
N = 512
win = es.Windowing(type='hann', normalized=False, zeroPhase=False, size=N)(np.ones(N, dtype=np.float32))
mb = es.MelBands(numberBands=96, sampleRate=16000, highFrequencyBound=8000, lowFrequencyBound=0, inputSize=257, weighting='linear', normalize='unit_tri', warpingFormula='slaneyMel', type='power')
M = np.zeros((96, 257), dtype=np.float64)
for k in range(257):
    sp = np.zeros(257, dtype=np.float32); sp[k] = 1.0
    M[:, k] = mb(sp)
# sparse rows: [start, weights...]
rows = []
for b in range(96):
    nz = np.nonzero(M[b])[0]
    s, e = (int(nz[0]), int(nz[-1]) + 1) if len(nz) else (0, 0)
    rows.append([s, [float(np.float32(x)) for x in M[b, s:e]]])
# check: window formula
i = np.arange(N); hann = 0.5 - 0.5*np.cos(2*np.pi*i/(N-1))
print('window max diff vs (N-1) hann', np.abs(win - hann).max(), ' vs N hann', np.abs(win - (0.5-0.5*np.cos(2*np.pi*i/N))).max())
# verify full pipeline equals TensorflowInputMusiCNN using numpy fft
rng = np.random.default_rng(3)
fr = rng.standard_normal(N).astype(np.float32) * 0.2
ref = es.TensorflowInputMusiCNN()(fr)
mag = np.abs(np.fft.rfft(fr * win))
mine = np.log10(1 + 10000 * (M @ (mag**2)))
print('pipeline max err', np.abs(mine - ref).max())
js = "/* Generated by tools/ml/make_melbank.py from Essentia's MelBands (96 bands, 16 kHz, 512-point FFT, slaney, unit_tri,\n   power) — the exact front end of the Essentia MusiCNN / Discogs-EffNet models. [start bin, weights…] per band. */\n"
js += "export const WINDOW = Float32Array.from(" + json.dumps([float(x) for x in win]) + ");\n"
js += "export const MEL = " + json.dumps(rows, separators=(',', ':')) + ";\n"
open(pathlib.Path(__file__).resolve().parents[2] / 'theme/js/ml/melbank.js', 'w').write(js)
print(len(js))
