"""
Builds theme/js/icons-win.js: the .ico images Windows needs for the taskbar thumbnail buttons and
the tray icon (the bridge takes raw Base64 .ico). Glyphs are drawn large and downsampled, white,
like the system's own media buttons; the tray icon comes from installer/assets/gatefold-256.png.

  python tools/make_win_icons.py
"""
import base64, io, math
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
S = 256                      # drawing size
SIZES = [(16, 16), (20, 20), (24, 24), (32, 32)]

def canvas():
    im = Image.new('RGBA', (S, S), (0, 0, 0, 0)); return im, ImageDraw.Draw(im)

def tri(d, x0, y0, x1, y1, right=True):
    pts = [(x0, y0), (x1, (y0 + y1) / 2), (x0, y1)] if right else [(x1, y0), (x0, (y0 + y1) / 2), (x1, y1)]
    d.polygon(pts, fill='white')

def rbar(d, x0, y0, x1, y1, r=14):
    d.rounded_rectangle((x0, y0, x1, y1), radius=r, fill='white')

def play():
    im, d = canvas(); tri(d, 70, 44, 214, 212); return im
def pause():
    im, d = canvas(); rbar(d, 62, 48, 112, 208); rbar(d, 144, 48, 194, 208); return im
def prev():
    im, d = canvas(); rbar(d, 46, 52, 82, 204, 10); tri(d, 84, 52, 210, 204, right=False); return im
def nxt():
    im, d = canvas(); rbar(d, 174, 52, 210, 204, 10); tri(d, 46, 52, 172, 204); return im

def heart_path(scale=1.0):
    pts = []
    for i in range(361):
        t = math.radians(i)
        x = 16 * math.sin(t) ** 3
        y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
        pts.append((128 + x * 6.6 * scale, 122 - y * 6.6 * scale))
    return pts

def heart(filled):
    im, d = canvas()
    if filled:
        d.polygon(heart_path(), fill='white')
    else:
        d.polygon(heart_path(), fill='white')
        hole = Image.new('L', (S, S), 0); ImageDraw.Draw(hole).polygon(heart_path(0.72), fill=255)
        im.putalpha(Image.composite(Image.new('L', (S, S), 0), im.getchannel('A'), hole))
    return im

def ico(im):
    buf = io.BytesIO()
    im.save(buf, format='ICO', sizes=SIZES)
    return base64.b64encode(buf.getvalue()).decode()

icons = {'prev': prev(), 'play': play(), 'pause': pause(), 'next': nxt(), 'heart': heart(False), 'heartFilled': heart(True)}
out = {k: ico(v) for k, v in icons.items()}
tray = Image.open(ROOT / 'installer/assets/gatefold-256.png').convert('RGBA')
buf = io.BytesIO(); tray.save(buf, format='ICO', sizes=[(16, 16), (20, 20), (24, 24), (32, 32), (48, 48)]); out['tray'] = base64.b64encode(buf.getvalue()).decode()

js = ['/* Generated by tools/make_win_icons.py — .ico images (raw Base64) for the taskbar buttons and the tray. */']
for k, v in out.items(): js.append(f"export const {k} = '{v}';")
(ROOT / 'theme/js/icons-win.js').write_text('\n'.join(js) + '\n', encoding='utf-8')
for k, v in icons.items(): v.resize((64, 64), Image.LANCZOS).save(ROOT / f'tools/.preview-{k}.png') if False else None
print({k: len(v) for k, v in out.items()})
